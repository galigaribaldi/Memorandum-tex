package contract

import (
	"path"
	"strings"
)

// Files of a template (contract §9 B4 and §12 V32). This is the only list:
// the folder validation of inkt and bundle.SafeExtract both use it, so what
// is rejected when publishing is exactly what is rejected when extracting.

// allowedExtensions are matched exactly, in lowercase: "Figura.PNG" is not
// allowed (rename it to figura.png), which also keeps names portable.
var allowedExtensions = map[string]bool{
	".tex": true, ".sty": true, ".cls": true, ".bst": true, ".bib": true, ".bbx": true, ".cbx": true,
	".lbx": true, ".cfg": true, ".def": true, ".md": true, ".txt": true, ".json": true, ".png": true,
	".jpg": true, ".jpeg": true, ".pdf": true, ".eps": true, ".svg": true, ".otf": true, ".ttf": true,
}

// textExtensions are checked for UTF-8, BOM and CRLF (V38).
var textExtensions = map[string]bool{
	".tex": true, ".sty": true, ".cls": true, ".bst": true, ".bib": true, ".bbx": true, ".cbx": true,
	".lbx": true, ".cfg": true, ".def": true, ".md": true, ".txt": true, ".json": true, ".svg": true,
}

// latexSourceExtensions are scanned for paths, ink-params, \providecommand
// and shell escape (V35–V37, V39).
var latexSourceExtensions = map[string]bool{".tex": true, ".sty": true, ".cls": true}

// Names that only the bundle may contain: inkt bundle generates them.
const (
	LicenseFileName = "LICENSE"
	MetaFileName    = ".creative-ink-meta"
)

// AllowedBundleFile reports whether a file name (the last path element) may
// be inside a bundle (B4).
func AllowedBundleFile(name string) bool {
	if name == LicenseFileName || name == MetaFileName {
		return true
	}
	return AllowedSourceFile(name)
}

// AllowedSourceFile reports whether a file name may be in a template's src/
// (V32): the extensions of B4, without hidden files, LICENSE or
// .creative-ink-meta (those two are generated by inkt bundle).
func AllowedSourceFile(name string) bool {
	if strings.HasPrefix(name, ".") || IsLatexmkrc(name) {
		return false
	}
	return allowedExtensions[path.Ext(name)]
}

// IsLatexmkrc reports whether name is a latexmk rc file in any letter case:
// on macOS and Windows ".LATEXMKRC" is the same file latexmk reads (B4).
func IsLatexmkrc(name string) bool {
	l := strings.ToLower(name)
	return l == ".latexmkrc" || l == "latexmkrc"
}

// IsTextFile reports whether the file is text (V38 applies).
func IsTextFile(name string) bool { return textExtensions[path.Ext(name)] }

// IsLaTeXSource reports whether the file is LaTeX code (.tex, .sty, .cls).
func IsLaTeXSource(name string) bool { return latexSourceExtensions[path.Ext(name)] }
